def load_csv(path: Path):
    with open(path, "r", encoding="utf-8") as f:
        return list(csv.DictReader(f))

def format_ci(mean_str: str, low_str: str, high_str: str, fmt: str = ".4f") -> str:
    m = float(mean_str)
    l = float(low_str)
    h = float(high_str)
    return f"{m:{fmt}} [{l:{fmt}}, {h:{fmt}}]"

