"""
experiments/generate_results_md.py

Generates experiments/RESULTS.md strictly by reading from CSV files in experiments/results/.
Every number comes directly from a CSV cell.
No subjective interpretation or claims of success.
Labels previous tables as "before duplicate handling" and presents all new tables.
"""

import csv
