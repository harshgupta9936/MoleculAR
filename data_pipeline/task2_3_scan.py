import sqlite3
from rdkit import Chem
from rdkit.Chem import Descriptors
from task2_2_pull import fetch_pubchem_bulk, standardize_smiles

def main():
    conn = sqlite3.connect('drugrepo.db')
    cursor = conn.cursor()
    
    # 1. Add DrugBank provenance
    cursor.execute("SELECT chembl_id FROM crosswalk WHERE drugbank_id IS NOT NULL")
    mapped_db = cursor.fetchall()
    print(f"Adding 'DrugBank' source to {len(mapped_db)} ChEMBL IDs...")
    for (cid,) in mapped_db:
        cursor.execute("UPDATE drugs SET source = source || ', DrugBank' WHERE chembl_id = ? AND source NOT LIKE '%DrugBank%'", (cid,))
        
    # 2. Re-fetch and Insert 23 new PubChem drugs
    # Wait, earlier they were generated by pc_new.
    # We will fetch all mapped PubChem SMILES and do the logic again.
    cursor.execute("SELECT chembl_id, pubchem_cid FROM crosswalk WHERE pubchem_cid IS NOT NULL")
    mapped_pc = cursor.fetchall()
    cid_to_chembl = {row[1]: row[0] for row in mapped_pc}
    cids_to_fetch = list(cid_to_chembl.keys())
    
    print("Refetching PubChem SMILES to insert the 23 new variants...")
    pc_smiles_dict = fetch_pubchem_bulk(cids_to_fetch)
    
    # Existing inchis
    cursor.execute("SELECT chembl_id, smiles, drug_name FROM drugs")
    chembl_drugs = cursor.fetchall()
    existing_inchis = {}
    for cid, smiles, name in chembl_drugs:
        ikey = standardize_smiles(smiles)
        if ikey:
            existing_inchis[ikey] = (cid, name)
            
    pc_processed_inchis = set()
    inserted_count = 0
    
    for pcid, smiles in pc_smiles_dict.items():
        if pcid in ['10176082', '6451240']:
            # Hold Aluminum Hydroxide and Aluminum Chloride
            continue
            
        ikey = standardize_smiles(smiles)
        if not ikey: continue
        
        expected_chembl = cid_to_chembl.get(pcid)
        
        if ikey in existing_inchis:
            # We already updated source for these in task2_2_pull (except the cross-wires which we hold/accept)
            pass
        elif ikey in pc_processed_inchis:
            pass
        else:
            # New variant!
            pc_processed_inchis.add(ikey)
            cursor.execute("SELECT drug_name, atc_category, indication, generic_base_name FROM drugs WHERE chembl_id = ?", (expected_chembl,))
            row = cursor.fetchone()
            if row:
                dname, atc, ind, gbn = row
                new_cid = f"PUBCHEM_{pcid}"
                cursor.execute("""
                    INSERT INTO drugs (chembl_id, drug_name, smiles, atc_category, indication, hubness_score, hubness_percentile, market_status, generic_base_name, source)
                    VALUES (?, ?, ?, ?, ?, NULL, NULL, 'Active (US)', ?, 'PubChem')
                """, (new_cid, dname + " (Stereoisomer)", smiles, atc, ind, gbn))
                inserted_count += 1

    conn.commit()
    print(f"Inserted {inserted_count} new stereoisomer variants.")
    
    # 3. Check Water and Sodium Chloride
    print("\n--- Cross-wire Verification ---")
    cursor.execute("SELECT chembl_id, drug_name FROM drugs WHERE chembl_id IN ('CHEMBL1098659', 'CHEMBL1200574')")
    print("Existing inorganic matches in DB:", cursor.fetchall())
    
    # 4. Scan for likely-trivial/inorganic entries
    print("\n--- Scanning for Trivial/Inorganic Entries ---")
    cursor.execute("SELECT chembl_id, drug_name, smiles, generic_base_name FROM drugs")
    all_drugs = cursor.fetchall()
    
    trivial_candidates = []
    
    for row in all_drugs:
        cid, name, smiles, base = row
        if not smiles: continue
        
        is_trivial = False
        reason = ""
        
        # Check no carbons
        if 'c' not in smiles.lower():
            is_trivial = True
            reason = "No carbon (Inorganic)"
        else:
            try:
                mol = Chem.MolFromSmiles(smiles)
                if mol:
                    hw = Descriptors.HeavyAtomCount(mol)
                    mw = Descriptors.MolWt(mol)
                    if mw < 60:
                        is_trivial = True
                        reason = f"Low MW ({mw:.1f})"
                    elif hw < 4:
                        is_trivial = True
                        reason = f"Few heavy atoms ({hw})"
            except:
                pass
                
        if is_trivial:
            trivial_candidates.append((cid, name, base, reason, smiles))
            
    print(f"Found {len(trivial_candidates)} likely-trivial candidates:")
    for cand in trivial_candidates:
        print(f"[{cand[0]}] {cand[1]} | {cand[3]} | SMILES: {cand[4]}")
        
    conn.close()

if __name__ == "__main__":
    main()
